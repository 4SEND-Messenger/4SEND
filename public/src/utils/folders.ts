const STORAGE_KEY = '4send_folders';

export interface ChatFolder {
  id: string;
  name: string;
  icon: string;
  chatUsernames: string[];
}

export function getFolders(): ChatFolder[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

export function saveFolders(folders: ChatFolder[]): void {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(folders));
}

export function createFolder(name: string, icon: string): ChatFolder {
  return {
    id: crypto.randomUUID(),
    name,
    icon,
    chatUsernames: [],
  };
}

export function addChatToFolder(username: string, folderId: string): void {
  const folders = getFolders();
  for (const f of folders) {
    if (f.id === folderId) {
      if (!f.chatUsernames.includes(username)) {
        f.chatUsernames.push(username);
      }
    } else {
      f.chatUsernames = f.chatUsernames.filter(u => u !== username);
    }
  }
  saveFolders(folders);
}

export function removeChatFromFolder(username: string): void {
  const folders = getFolders();
  for (const f of folders) {
    f.chatUsernames = f.chatUsernames.filter(u => u !== username);
  }
  saveFolders(folders);
}

export function getFolderForChat(username: string): ChatFolder | undefined {
  return getFolders().find(f => f.chatUsernames.includes(username));
}

export function deleteFolder(id: string): void {
  saveFolders(getFolders().filter(f => f.id !== id));
}

const ENABLED_KEY = '4send_folders_enabled';

export function isFoldersEnabled(): boolean {
  return localStorage.getItem(ENABLED_KEY) === '1';
}

export function setFoldersEnabled(enabled: boolean): void {
  localStorage.setItem(ENABLED_KEY, enabled ? '1' : '0');
}

